// Imports the traced route lines in assets/data/ into a seed module (RR1).
// Run on the PC with the installed tsx:
//   npx tsx scripts/import-route.ts           dry run: report only, writes nothing
//   npx tsx scripts/import-route.ts --write   writes src/data/seed/routes.generated.ts
// The app never reads the GeoJSON files: it reads the generated module, so all parsing,
// simplification and length work happens here, once.

import * as fs from 'node:fs';
import * as path from 'node:path';

import { TILESET } from '../src/data/map/tileset';
import { importRoute, type ImportedRoute, type ReturnRule } from '../src/shared/routing/routeImport';

type RouteSource = {
  code: string;
  name: string;
  file: string;
  // PUJ route map, October 2026: R3 runs the same road both ways ("vice versa").
  // R4 and R5 return by other roads; the traced files are the first part of each return leg
  // (De Oro toward R. Calo; Santo Niño toward J C Aquino Ave), decided by Emjay on 2026-10-04.
  rule: ReturnRule;
};

const SOURCES: RouteSource[] = [
  { code: 'R3', name: 'Ampayon-Libertad', file: 'route_3_primary.geojson', rule: 'vice_versa' },
  { code: 'R4', name: 'De Oro', file: 'route_4_primary.geojson', rule: 'partial_return' },
  { code: 'R5', name: 'Santo Niño', file: 'route_5_primary.geojson', rule: 'partial_return' },
];

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'data', 'seed', 'routes.generated.ts');
const write = process.argv.includes('--write');

const results: { source: RouteSource; route: ImportedRoute }[] = SOURCES.map((source) => {
  const geojson: unknown = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets', 'data', source.file), 'utf8'));
  return { source, route: importRoute(geojson, source.rule, TILESET.bounds) };
});

for (const { source, route } of results) {
  console.log(`\n${source.code} ${source.name} (${source.file})`);
  console.log(`  mode ${route.directionMode}; ${route.note}`);
  console.log(`  points ${route.pointsBefore} -> ${route.pointsAfter}; largest deviation ${route.maxDeviationM.toFixed(2)} m`);
  for (const d of route.directions) {
    console.log(`  ${d.direction}: ${d.lengthKm.toFixed(2)} km${d.derived ? ' (derived)' : ''}${d.partial ? ' (partial)' : ''}`);
  }
  for (const issue of route.issues) console.log(`  ${issue.level.toUpperCase()}: ${issue.message}`);
}

const failed = results.filter(({ route }) => route.issues.some((issue) => issue.level === 'fail'));
if (failed.length > 0) {
  console.log(`\nFAILED: ${failed.map(({ source }) => source.code).join(', ')}. Nothing written.`);
  process.exit(1);
}
if (!write) {
  console.log('\nDry run: nothing written. Add --write to write the seed module.');
  process.exit(0);
}

const round = (n: number) => Math.round(n * 1e6) / 1e6;
const body = results
  .map(({ source, route }) =>
    route.directions
      .map(
        (d) => `  {
    routeCode: '${source.code}',
    routeName: '${source.name}',
    direction: '${d.direction}',
    directionMode: '${route.directionMode}',
    derived: ${d.derived},
    partial: ${d.partial},
    lengthKm: ${d.lengthKm.toFixed(3)},
    coordinates: ${JSON.stringify(d.coordinates.map((p) => [round(p[0]), round(p[1])]))},
  },`,
      )
      .join('\n'),
  )
  .join('\n');

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/import-route.ts from assets/data/*.geojson. Do not edit by hand.
// Traced by Emjay in Google My Maps (method to be confirmed by the user; see docs/route-trace.md).
// Pure data: no React Native or Expo imports.

export type GeneratedLine = {
  routeCode: string;
  routeName: string;
  direction: 'outbound' | 'return';
  directionMode: 'one_way' | 'two_way' | 'loop';
  // Made by reversing the traced line (R3 "vice versa")
  derived: boolean;
  // The traced leg stops before the Jeepney Terminal (R4, R5)
  partial: boolean;
  lengthKm: number;
  coordinates: [number, number][];
};

export const GENERATED_LINES: GeneratedLine[] = [
${body}
];
`,
);
console.log(`\nWrote ${path.relative(ROOT, OUT)}`);
