// NM1: writes supabase/functions/_shared/routeStops.generated.ts, each route's stops for the ingest
// function's stop passages (nodePassage.ts). The Edge Function can load files only from its own
// folder, so the app's route data is copied there; a test checks the copy is current. Rerun after
// the stops change (routes.generated.ts).
// Run: npx tsx scripts/server-route-stops.ts

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { SEED_STATIONS } from '../src/data/seed/routes';

const routes = [...new Set(SEED_STATIONS.flatMap((station) => station.routeCodes))].sort();
const lines = routes.map((route) => {
  const stops = SEED_STATIONS.filter((station) => station.routeCodes.includes(route)).map(
    (station) => `{ code: '${station.code}', lat: ${station.lat.toFixed(6)}, lon: ${station.lon.toFixed(6)} }`,
  );
  return `  ${route}: [\n    ${stops.join(',\n    ')},\n  ],`;
});

const text = `// GENERATED by scripts/server-route-stops.ts from src/data/seed. Do not edit by hand.
// NM1: each route's stops, for the ingest function's stop passages (nodePassage.ts).

import type { PassStop } from './nodePassage.ts';

export const ROUTE_STOPS: Record<string, PassStop[]> = {
${lines.join('\n')}
};
`;

const out = join(__dirname, '..', 'supabase', 'functions', '_shared', 'routeStops.generated.ts');
writeFileSync(out, text);
console.log(`${routes.length} routes written to ${out}`);
