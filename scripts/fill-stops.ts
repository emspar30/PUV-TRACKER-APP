// CA2-0: writes src/data/seed/fillStops.generated.ts, the fill stops on long stretches of route line
// with no stop (src/shared/routing/fillStops.ts). Rerun after the route lines or stops change; the
// same data gives the same stops and codes. Review the list by hand afterwards: rename or move a
// stop in docs, then rerun.
// Run: npx tsx scripts/fill-stops.ts

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { MAP_PLACES } from '../src/data/seed/places';
import { GENERATED_LINES, GENERATED_STATIONS } from '../src/data/seed/routes.generated';
import { fillStops } from '../src/shared/routing/fillStops';

const result = fillStops(
  GENERATED_LINES.map((line) => ({ routeCode: line.routeCode, coordinates: line.coordinates })),
  GENERATED_STATIONS,
  MAP_PLACES.map(([name, , group, lat, lon]) => ({ name, group, lat, lon })),
);

const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const rows = result.stops.map(
  (stop) => `  { code: '${stop.code}', name: ${quote(stop.name)}, lat: ${stop.lat.toFixed(6)}, lon: ${stop.lon.toFixed(6)}, routeCodes: [${stop.routeCodes.map((r) => `'${r}'`).join(', ')}] },`,
);
const extras = Object.entries(result.extraRoutes).map(([code, routes]) => `  ${code}: [${routes.map((r) => `'${r}'`).join(', ')}],`);

const text = `// GENERATED by scripts/fill-stops.ts from routes.generated.ts and the map places. Do not edit by hand.
// CA2-0: stops on long stretches of route line, so no point of a line is more than 300 m from a stop
// of its route (src/shared/routing/fillStops.ts). Four-letter codes starting with F; real stops have three.
// Names are from OpenStreetMap places (ODbL).

export type GeneratedFillStop = {
  code: string;
  name: string;
  lat: number;
  lon: number;
  routeCodes: string[];
};

export const GENERATED_FILL_STOPS: GeneratedFillStop[] = [
${rows.join('\n')}
];

// Real stops another route also uses, because its fill stop would have sat within 100 m of them
export const GENERATED_EXTRA_ROUTES: Record<string, string[]> = {
${extras.join('\n')}
};
`;

const out = join(__dirname, '..', 'src', 'data', 'seed', 'fillStops.generated.ts');
writeFileSync(out, text);
const perRoute = new Map<string, number>();
for (const stop of result.stops) for (const route of stop.routeCodes) perRoute.set(route, (perRoute.get(route) ?? 0) + 1);
console.log(`${result.stops.length} fill stops written to ${out}`);
console.log([...perRoute].map(([route, n]) => `${route} +${n}`).join(', '), '| real stops taken over:', JSON.stringify(result.extraRoutes));
