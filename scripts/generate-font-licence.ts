// Embeds the font licence (assets/glyphs/glyphs-v1/OFL.txt) in a TypeScript module, so the app can
// show it on About → Licences (SIL OFL 1.1: the copyright notice and the licence travel with the fonts).
// Metro does not bundle .txt files, which is why the text is generated into code. Run on the PC:
//   npx tsx scripts/generate-font-licence.ts
// A unit test fails if the generated module and the text file ever differ.

import * as fs from 'node:fs';
import * as path from 'node:path';

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'assets', 'glyphs', 'glyphs-v1', 'OFL.txt');
const OUT = path.join(ROOT, 'src', 'data', 'licences', 'fontLicence.generated.ts');

const text = fs.readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');
const body = [
  '// GENERATED by scripts/generate-font-licence.ts from assets/glyphs/glyphs-v1/OFL.txt. Do not edit.',
  '',
  `export const FONT_LICENCE_TEXT = ${JSON.stringify(text)};`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, 'utf8');
console.log(`Wrote ${path.relative(ROOT, OUT)} (${text.length} characters)`);
